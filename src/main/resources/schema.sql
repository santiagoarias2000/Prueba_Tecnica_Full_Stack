-- Esquema H2 de polizas-api. Hibernate solo lo valida (ddl-auto: validate).
DROP TABLE IF EXISTS riesgo;
DROP TABLE IF EXISTS poliza;

CREATE TABLE poliza (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_poliza         VARCHAR(30)    NOT NULL,
    tipo                  VARCHAR(20)    NOT NULL,
    estado                VARCHAR(20)    NOT NULL,
    tomador               VARCHAR(200)   NOT NULL,
    fecha_inicio_vigencia DATE           NOT NULL,
    fecha_fin_vigencia    DATE           NOT NULL,
    meses_vigencia        INTEGER        NOT NULL,
    valor_canon           NUMERIC(15, 2) NOT NULL,
    valor_prima           NUMERIC(15, 2) NOT NULL,
    version               BIGINT         DEFAULT 0 NOT NULL,
    creado_en             TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actualizado_en        TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_poliza_numero UNIQUE (numero_poliza),
    CONSTRAINT ck_poliza_tipo CHECK (tipo IN ('INDIVIDUAL', 'COLECTIVA')),
    CONSTRAINT ck_poliza_estado CHECK (estado IN ('ACTIVA', 'RENOVADA', 'CANCELADA')),
    CONSTRAINT ck_poliza_meses CHECK (meses_vigencia > 0),
    CONSTRAINT ck_poliza_vigencia CHECK (fecha_fin_vigencia >= fecha_inicio_vigencia),
    CONSTRAINT ck_poliza_valores CHECK (valor_canon >= 0 AND valor_prima >= 0)
);

CREATE TABLE riesgo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poliza_id          BIGINT         NOT NULL,
    descripcion        VARCHAR(200)   NOT NULL,
    arrendatario       VARCHAR(200)   NOT NULL,
    arrendador         VARCHAR(200)   NOT NULL,
    valor_canon        NUMERIC(15, 2) NOT NULL,
    estado             VARCHAR(20)    NOT NULL,
    fecha_inicio       DATE           NOT NULL,
    fecha_cancelacion  DATE,
    motivo_cancelacion VARCHAR(300),
    CONSTRAINT fk_riesgo_poliza FOREIGN KEY (poliza_id) REFERENCES poliza (id),
    CONSTRAINT ck_riesgo_estado CHECK (estado IN ('ACTIVO', 'CANCELADO')),
    CONSTRAINT ck_riesgo_canon CHECK (valor_canon > 0),
    CONSTRAINT ck_riesgo_cancelacion CHECK (estado = 'ACTIVO' OR fecha_cancelacion IS NOT NULL)
);

CREATE INDEX idx_poliza_tipo_estado ON poliza (tipo, estado);
CREATE INDEX idx_riesgo_poliza_estado ON riesgo (poliza_id, estado);
